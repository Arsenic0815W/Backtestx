#!/usr/bin/env python3
"""Turns the raw outputs of tools/run_benchmarks.ps1 into docs/BENCHMARKS.md (tables only; no number is typed by hand).

    python -I tools/bench_report.py RAW_DIR OUT.md [NOTES.md]

RAW_DIR holds env.json and run1.json .. runN.json (bt_bench --json). Refuses to write anything if the runs disagree on a result hash
or sweep signature (a benchmark whose answer changed means nothing). NOTES.md (hand-written discussion) is appended verbatim.
"""
import glob
import json
import os
import statistics
import sys


def med(v):
    return statistics.median(v)


def main(argv):
    if len(argv) < 2:
        print(__doc__)
        return 2
    raw, out = argv[0], argv[1]
    notes = argv[2] if len(argv) > 2 else None
    baseline = argv[3] if len(argv) > 3 else None
    with open(os.path.join(raw, "env.json"), encoding="utf-8-sig") as f:
        env = json.load(f)
    runs = []
    for p in sorted(glob.glob(os.path.join(raw, "run*.json"))):
        with open(p, encoding="utf-8-sig") as f:
            runs.append(json.load(f))
    if len(runs) < 3:
        print("ERROR: need at least 3 runs")
        return 1
    for r in runs:
        if not r["optimised_build"]:
            print("ERROR: a run came from an unoptimised build")
            return 1
    # consistency across runs
    for k, s0 in enumerate(runs[0]["single"]):
        for r in runs[1:]:
            if r["single"][k]["result_hash"] != s0["result_hash"] or r["single"][k]["trades"] != s0["trades"]:
                print(f"ERROR: workload '{s0['name']}' gave a different result in another run")
                return 1
    if any(r["sweep"]["signature"] != runs[0]["sweep"]["signature"] for r in runs):
        print("ERROR: the sweep signature differs between runs")
        return 1

    L = []
    L.append("# BENCHMARKS\n")
    L.append("*Generated by `tools/run_benchmarks.ps1` + `tools/bench_report.py`. Every number in the tables comes from the raw `bt_bench --json` "
             "output in `docs/bench_runs/`. Synthetic data only; nothing here says anything about real markets or about trading performance.*\n")
    L.append("## Environment (captured by the script)\n")
    L.append("| item | value |\n|---|---|")
    for k, v in env.items():
        if k == "thread_orders":
            continue
        L.append(f"| {k} | {v} |")
    L.append(f"| thread-count order in each run | " + "; ".join(f"run {i + 1}: {o}" for i, o in enumerate(env["thread_orders"])) + " |")
    L.append(f"| bt_bench said | {runs[0]['tool']}, hardware_concurrency {runs[0]['hardware_concurrency']}, optimised {runs[0]['optimised_build']}, NDEBUG {runs[0]['ndebug']} |")
    L.append("")
    L.append("## What is measured\n")
    L.append("- **Timed:** `run_backtest` (engine + analytics) and `run_sweep`, nothing else. Synthetic data generation, calendar alignment and "
             "result hashing are outside the timed regions; no file I/O or report writing is involved (the CLI is not used).\n"
             "- **A \"bar\" is one symbol-day** (symbols x calendar days). Every bar is evaluated (no warm-up window), so bars/sec counts all of them.\n"
             "- **Method:** each unit is repeated; the first repetition is discarded; repetitions continue until at least "
             f"{runs[0]['min_seconds']} s of timed work and 5 repetitions; the **median repetition** is reported (min and max are in the raw JSON).\n"
             "- **Guards:** every repetition's result hash must be identical, every sweep grid point's hash must be identical across repetitions, "
             "thread counts and the three runs, trades must be > 0, and the build must be optimised. Otherwise the run aborts.\n"
             "- **Sweeps** use no in-sample/out-of-sample split, so one grid point = one backtest.\n")
    L.append("## Single backtest\n")
    L.append("| workload | strategy | bars | fills | trades | result hash |\n|---|---|---:|---:|---:|---|")
    for s in runs[0]["single"]:
        L.append(f"| {s['name']} | {s['strategy']} | {s['bars']:,} | {s['fills']:,} | {s['trades']:,} | `{s['result_hash']}` |")
    L.append("")
    L.append("Median repetition time and throughput, all runs shown:\n")
    L.append("| workload | " + " | ".join(f"run {i + 1} ms | run {i + 1} bars/s" for i in range(len(runs))) + " | median of runs bars/s | min..max bars/s |")
    L.append("|---|" + "---:|" * (2 * len(runs) + 2))
    for k, s0 in enumerate(runs[0]["single"]):
        cells, bps = [], []
        for r in runs:
            s = r["single"][k]
            cells += [f"{s['median_ms']:.3f}", f"{s['bars_per_sec_median']:,.0f}"]
            bps.append(s["bars_per_sec_median"])
        L.append(f"| {s0['name']} | " + " | ".join(cells) + f" | {med(bps):,.0f} | {min(bps):,.0f} .. {max(bps):,.0f} |")
    L.append("")
    sw0 = runs[0]["sweep"]
    L.append("## Sweep throughput\n")
    L.append(f"Workload: {sw0['name']}; {sw0['grid_points']} grid points ({sw0['runnable_points']} runnable), {sw0['bars_per_run']:,} bars per run. "
             f"Sweep signature (hash of all row hashes), identical in every run and at every thread count: `{sw0['signature']}`.\n")
    threads = sorted({t["threads_requested"] for t in sw0["per_thread"]})

    def rps(r, th):
        return [t for t in r["sweep"]["per_thread"] if t["threads_requested"] == th][0]

    L.append("| threads | " + " | ".join(f"run {i + 1} runs/s" for i in range(len(runs))) + " | median of runs | min..max | speedup vs 1 thread | efficiency |")
    L.append("|---:|" + "---:|" * (len(runs) + 4))
    base = med([rps(r, threads[0])["runs_per_sec_median"] for r in runs])
    rows = []
    for th in threads:
        vals = [rps(r, th)["runs_per_sec_median"] for r in runs]
        m = med(vals)
        sp = m / base
        rows.append((th, vals, m, sp))
        eff = sp / (th / threads[0]) * 100
        L.append(f"| {th} | " + " | ".join(f"{v:,.0f}" for v in vals) + f" | {m:,.0f} | {min(vals):,.0f} .. {max(vals):,.0f} | {sp:.2f}x | {eff:.0f}% |")
    L.append("")
    L.append(f"Speedup = median-of-runs runs/s at N threads / at {threads[0]} thread(s); efficiency = speedup / (N / {threads[0]}). "
             "Per-run order of thread counts is rotated (see the environment table) so thermal drift is not baked into the curve.\n")
    if baseline and os.path.exists(baseline):
        with open(baseline, encoding="utf-8-sig") as f:
            bl = json.load(f)
        L.append("## Previous run for comparison (battery power)\n")
        L.append(bl["_note"] + " Difference = (this run - previous) / previous, on the median-of-runs figures.\n")
        L.append("| measurement | previous | this run | difference |\n|---|---:|---:|---:|")
        for k, s0 in enumerate(runs[0]["single"]):
            now = med([r["single"][k]["bars_per_sec_median"] for r in runs])
            prev = bl["single_bars_per_sec"][s0["name"]]
            L.append(f"| {s0['name']} bars/s | {prev:,.0f} | {now:,.0f} | {(now / prev - 1) * 100:+.1f}% |")
        for th, vals, m, sp in rows:
            prev = bl["sweep_runs_per_sec"][str(th)]
            L.append(f"| sweep runs/s, {th} thread(s) | {prev:,.0f} | {m:,.0f} | {(m / prev - 1) * 100:+.1f}% |")
        L.append("")
    text = "\n".join(L) + "\n"
    if notes and os.path.exists(notes):
        with open(notes, encoding="utf-8") as f:
            text += "\n" + f.read()
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
